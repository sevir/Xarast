//! Rebuilding a damaged package (`research/06 §10.4`; phase 6 F6.8).
//!
//! [`XarastReader::open`](crate::XarastReader::open) is strict by design: a
//! package whose end record or central directory is damaged is refused.
//! This module is the separate path for those files. It never trusts the
//! central directory at all. It scans the whole byte string for `PK\x03\x04`
//! local headers, recovers what each one holds, validates every entry and
//! writes a fresh package with [`PackageWriter`].
//!
//! # Algorithm
//!
//! 1. **Scan.** Every occurrence of the local-header signature is a
//!    candidate. The 30-byte header gives the name, flags, method and the
//!    declared CRC-32; the sizes are only hints. A DEFLATE entry is inflated
//!    from its data start and ends where the stream ends (so a missing or
//!    lying size, or a data descriptor, does not matter); a STORED entry takes
//!    its declared size, or ends at a data descriptor whose CRC matches.
//!    After a complete entry the scan resumes behind it, so a package nested
//!    inside a resource is not mistaken for entries of this one; after a
//!    failed candidate it resumes one byte further on.
//! 2. **Validate.** An entry is *verified* when it is complete and its CRC-32
//!    matches. When `META-INF/manifest.xml` is itself readable, its BLAKE3
//!    digests are checked too. Resources are self-describing: the hash in
//!    `resources/…/b3-<hash>.<ext>` must be the hash of the content.
//! 3. **Decide.** `document.svg` is kept even when it does not verify (a
//!    truncated or altered document is what the partial XML reader exists
//!    for; see [`crate::partial`]); everything else that does not verify is
//!    dropped and reported. A missing or unverified `meta.xml` is replaced by
//!    a minimal one. Thumbnails and previews that fail are dropped (they are
//!    regenerable). A resource that is dropped leaves a dangling reference,
//!    which the document reader turns into a visible placeholder.
//! 4. **Rebuild.** `mimetype` and the manifest are regenerated by the
//!    writer; entries come out in the normative order with fresh digests.
//!
//! # Hostile input
//!
//! The input is attacker-controlled. Every inflate is capped by what is left
//! of the [`Limits::max_total_uncompressed`] budget, and that budget is
//! charged for rejected candidates too, so overlapping fake headers cannot
//! multiply the work. Per-entry ratio, the entry count and the manifest size
//! use the same [`Limits`] as the strict reader. Nothing here indexes with
//! `[]` or does unchecked arithmetic.

#![deny(clippy::arithmetic_side_effects)]

