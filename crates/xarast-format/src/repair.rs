/// The local file header signature.
const LOCAL_SIG: [u8; 4] = *b"PK\x03\x04";
/// The data descriptor signature.
const DESCRIPTOR_SIG: [u8; 4] = *b"PK\x07\x08";
/// Fixed part of a local file header.
const LOCAL_LEN: usize = 30;
/// How many descriptor candidates a STORED entry of unknown size tries.
const MAX_DESCRIPTOR_TRIES: usize = 64;

/// Why a package could not be rebuilt.
#[derive(Debug, thiserror::Error)]
pub enum RepairError {
    /// Reading or writing a file failed.
    #[error("I/O error: {0}")]
    Io(#[from] io::Error),
    /// Not one local header with a usable name was found.
    #[error("no ZIP entries could be recovered")]
    NoEntries,
    /// `document.svg` is not in what survived: there is nothing to rebuild a
    /// document from.
    #[error("document.svg could not be recovered")]
    NoDocument,
    /// The writer refused the rebuilt package.
    #[error("cannot write the rebuilt package: {0}")]
    Write(#[from] WriteError),
}

/// What happened to one recovered entry.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Verdict {
    /// Complete, CRC-32 correct, and the manifest digest (if any) matches.
    Verified,
    /// Complete and CRC-32 correct, with no digest to check it against.
    Unchecked,
    /// Complete and CRC-32 correct, but the manifest digest differs.
    DigestMismatch,
    /// Complete, but the CRC-32 differs.
    CrcMismatch,
    /// The data ends early: a truncated file or a lying size.
    Truncated,
    /// A resource whose content does not hash to its name.
    NameMismatch,
}

/// What the rebuild did with an entry.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Action {
    /// Carried into the new package as it was.
    Kept,
    /// Carried although it did not verify (only `document.svg`): the
    /// partial reader will do what it can.
    Salvaged,
    /// Not carried.
    Dropped,
    /// Not in the damaged file (or not verifiable): a minimal replacement
    /// was written.
    Replaced,
}

/// One line of the report.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EntryReport {
    /// The entry name.
    pub name: String,
    /// What was found.
    pub verdict: Verdict,
    /// What was done.
    pub action: Action,
    /// Bytes recovered (uncompressed).
    pub size: u64,
}

/// What [`repair`] did.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct RepairReport {
    /// `true` when the strict reader would have opened the input anyway.
    pub was_openable: bool,
    /// Local headers that gave a usable entry.
    pub entries_found: usize,
    /// Per-entry results, in the order they were found.
    pub entries: Vec<EntryReport>,
    /// Entries of the manifest that were not found in the file.
    pub manifest_rows_missing: Vec<String>,
    /// Whether the manifest could be read (digests were checked against it).
    pub manifest_used: bool,
    /// `document.svg` did not verify: expect the partial reader's warning.
    pub document_unverified: bool,
    /// Bytes of the rebuilt package.
    pub bytes_written: u64,
}

impl RepairReport {
    /// Entries that were not carried over.
    pub fn dropped(&self) -> impl Iterator<Item = &EntryReport> {
        self.entries.iter().filter(|e| e.action == Action::Dropped)
    }

    /// Whether anything was lost, replaced or doubtful.
    #[must_use]
    pub fn lossy(&self) -> bool {
        self.document_unverified
            || self.dropped().next().is_some()
            || self.entries.iter().any(|e| e.action == Action::Replaced)
    }
}

/// Options for [`repair`].
#[derive(Debug, Clone, Default)]
pub struct RepairOptions {
    /// Limits on what is inflated and how much is accepted.
    pub limits: Limits,
    /// How the new package is written.
    pub write: WriteOptions,
}

/// One entry found by the scan.
#[derive(Debug)]
struct Found {
    name: String,
    data: Vec<u8>,
    /// The stream or the stored bytes reached their end.
    complete: bool,
    /// Complete and the CRC-32 matches.
    crc_ok: bool,
}

/// A complete rebuild: the new package and the report.
#[derive(Debug)]
pub struct Repaired {
    /// The new package.
    pub bytes: Vec<u8>,
    /// What was done.
    pub report: RepairReport,
}

fn le16(b: &[u8], at: usize) -> Option<u16> {
    let s = b.get(at..at.checked_add(2)?)?;
    Some(u16::from_le_bytes([*s.first()?, *s.get(1)?]))
}

fn le32(b: &[u8], at: usize) -> Option<u32> {
    let s = b.get(at..at.checked_add(4)?)?;
    Some(u32::from_le_bytes([
        *s.first()?,
        *s.get(1)?,
        *s.get(2)?,
        *s.get(3)?,
    ]))
}

fn crc32(data: &[u8]) -> u32 {
    let mut c = Crc::new();
    c.update(data);
    c.sum()
}

/// Positions of every local-header signature at or after `from`.
fn next_signature(bytes: &[u8], from: usize) -> Option<usize> {
    let tail = bytes.get(from..)?;
    tail.windows(LOCAL_SIG.len())
        .position(|w| w == LOCAL_SIG)
        .and_then(|p| p.checked_add(from))
}

/// The outcome of reading one candidate.
struct Candidate {
    found: Found,
    /// Where the entry ends (including a descriptor), when it is complete.
    end: Option<usize>,
}

/// Inflates a raw DEFLATE stream from `input`, writing at most `cap` bytes.
/// Returns the output, the input consumed and whether the stream ended.
fn inflate(input: &[u8], cap: u64) -> (Vec<u8>, usize, bool) {
    let mut d = Decompress::new(false);
    let mut out: Vec<u8> = Vec::new();
    let cap = usize::try_from(cap).unwrap_or(usize::MAX);
    let mut ended = false;
    loop {
        let consumed = usize::try_from(d.total_in()).unwrap_or(usize::MAX);
        let Some(rest) = input.get(consumed..) else {
            break;
        };
        if out.len() >= cap {
            break;
        }
        let room = cap.saturating_sub(out.len()).min(64 << 10);
        let before_len = out.len();
        // `decompress_vec` appends into spare capacity.
        out.reserve(room);
        let before_in = d.total_in();
        let status = d.decompress_vec(rest, &mut out, FlushDecompress::None);
        let progressed = out.len() > before_len || d.total_in() > before_in;
        match status {
            Ok(Status::StreamEnd) => {
                ended = true;
                break;
            }
            Ok(_) if progressed => {}
            _ => break,
        }
    }
    out.truncate(cap);
    let used = usize::try_from(d.total_in()).unwrap_or(usize::MAX);
    (out, used, ended)
}

/// Reads the candidate whose local header starts at `at`.
fn read_candidate(bytes: &[u8], at: usize, budget: &mut u64, limits: &Limits) -> Option<Candidate> {
    let flags = le16(bytes, at.checked_add(6)?)?;
    let method = le16(bytes, at.checked_add(8)?)?;
    let crc = le32(bytes, at.checked_add(14)?)?;
    let usize32 = le32(bytes, at.checked_add(22)?)?;
    let name_len = usize::from(le16(bytes, at.checked_add(26)?)?);
    let extra_len = usize::from(le16(bytes, at.checked_add(28)?)?);
    let name_at = at.checked_add(LOCAL_LEN)?;
    let raw = bytes.get(name_at..name_at.checked_add(name_len)?)?;
    if flags & 1 != 0 || raw.last() == Some(&b'/') {
        return None; // encrypted, or a directory
    }
    validate_raw_name(raw, flags & (1 << 11) != 0).ok()?;
    let name = std::str::from_utf8(raw).ok()?.to_owned();
    let data_at = name_at.checked_add(name_len)?.checked_add(extra_len)?;
    let rest = bytes.get(data_at..)?;
    let has_descriptor = flags & (1 << 3) != 0;
    let cap = (*budget).min(limits.max_total_uncompressed);

    let (data, consumed, complete) = match method {
        0 => {
            let known = !has_descriptor || usize32 != 0;
            if known {
                let want = u64::from(usize32).min(cap);
                let want = usize::try_from(want).unwrap_or(usize::MAX);
                let take = rest.get(..want).unwrap_or(rest);
                let whole = take.len() == usize::try_from(usize32).unwrap_or(usize::MAX);
                (take.to_vec(), take.len(), whole)
            } else {
                // Unknown size: the descriptor says where it ends.
                let mut found = None;
                let mut tries = 0usize;
                let mut from = 0usize;
                while tries < MAX_DESCRIPTOR_TRIES {
                    let Some(p) = rest
                        .get(from..)
                        .and_then(|t| t.windows(4).position(|w| w == DESCRIPTOR_SIG))
                        .and_then(|p| p.checked_add(from))
                    else {
                        break;
                    };
                    tries = tries.saturating_add(1);
                    let body = rest.get(..p).unwrap_or_default();
                    if le32(rest, p.saturating_add(4)) == Some(crc32(body)) {
                        found = Some(body.len());
                        break;
                    }
                    from = p.saturating_add(1);
                }
                match found {
                    Some(n) => (
                        rest.get(..n).unwrap_or_default().to_vec(),
                        n,
                        n as u64 <= cap,
                    ),
                    None => (Vec::new(), 0, false),
                }
            }
        }
        8 => {
            let (out, used, ended) = inflate(rest, cap);
            (out, used, ended)
        }
        _ => return None,
    };

    // Charge the budget for the work, kept or not.
    *budget = budget.saturating_sub((data.len() as u64).max(1));
    // The strict reader's ratio rule: a stream that expands absurdly is a
    // bomb, not an entry.
    let compressed = consumed as u64;
    let size = data.len() as u64;
    if size > limits.ratio_floor
        && compressed
            .checked_mul(limits.max_entry_ratio)
            .is_none_or(|c| size > c)
    {
        return None;
    }

    let mut end = data_at.checked_add(consumed);
    let mut want_crc = crc;
    if complete && has_descriptor {
        // The descriptor may or may not carry its signature.
        let e = end?;
        let (crc_at, after) = if bytes.get(e..e.checked_add(4)?) == Some(&DESCRIPTOR_SIG) {
            (e.checked_add(4)?, e.checked_add(16)?)
        } else {
            (e, e.checked_add(12)?)
        };
        if let Some(c) = le32(bytes, crc_at) {
            want_crc = c;
            end = Some(after.min(bytes.len()));
        }
    }
    let crc_ok = complete && crc32(&data) == want_crc;
    Some(Candidate {
        found: Found {
            name,
            data,
            complete,
            crc_ok,
        },
        end: if complete { end } else { None },
    })
}

/// Scans `bytes` for local headers.
fn scan(bytes: &[u8], limits: &Limits) -> Vec<Found> {
    let mut out: Vec<Found> = Vec::new();
    let mut budget = limits.max_total_uncompressed;
    let mut at = 0usize;
    let max_entries = usize::try_from(limits.max_entries).unwrap_or(usize::MAX);
    while let Some(p) = next_signature(bytes, at) {
        if budget == 0 || out.len() >= max_entries {
            break;
        }
        match read_candidate(bytes, p, &mut budget, limits) {
            Some(c) => {
                let next = c.end.filter(|&e| e > p).unwrap_or(p.saturating_add(1));
                out.push(c.found);
                at = next;
            }
            None => at = p.saturating_add(1),
        }
    }
    out
}

/// A minimal `meta.xml` for a package whose own did not survive.
fn minimal_meta() -> Vec<u8> {
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <xarast:meta xmlns:xarast=\"{NS_XARAST}\" xarast:version=\"1.0\" \
         xarast:min-reader=\"1.0\"/>\n"
    )
    .into_bytes()
}

/// Rebuilds a package from whatever survives in `bytes`.
///
/// # Errors
///
/// [`RepairError::NoEntries`] or [`RepairError::NoDocument`] when nothing
/// usable is there, [`RepairError::Write`] when the writer refuses.
pub fn repair(bytes: &[u8], opts: &RepairOptions) -> Result<Repaired, RepairError> {
    let mut report = RepairReport {
        was_openable: crate::XarastReader::open_with(Cursor::new(bytes), opts.limits).is_ok(),
        ..RepairReport::default()
    };
    let found = scan(bytes, &opts.limits);
    report.entries_found = found.len();
    if found.is_empty() {
        return Err(RepairError::NoEntries);
    }

    // One survivor per name: a verified copy beats an unverified one, and
    // among equals the later (an appended update) wins.
    let mut best: HashMap<String, usize> = HashMap::new();
    for (i, f) in found.iter().enumerate() {
        let better = best
            .get(&f.name)
            .and_then(|&j| found.get(j))
            .is_none_or(|old| f.crc_ok || !old.crc_ok);
        if better {
            best.insert(f.name.clone(), i);
        }
    }
    let mut order: Vec<usize> = best.values().copied().collect();
    order.sort_unstable();

    let manifest = best
        .get(MANIFEST_ENTRY)
        .and_then(|&i| found.get(i))
        .filter(|f| f.crc_ok && f.data.len() as u64 <= opts.limits.max_manifest_size)
        .and_then(|f| Manifest::parse(&f.data, &opts.limits).ok());
    report.manifest_used = manifest.is_some();
    if let Some(m) = &manifest {
        report.manifest_rows_missing = m
            .entries
            .iter()
            .filter(|r| !best.contains_key(&r.full_path))
            .map(|r| r.full_path.clone())
            .collect();
    }
    let row_of = |name: &str| -> Option<&FileEntry> { manifest.as_ref().and_then(|m| m.entry(name)) };

    let mut w = PackageWriter::new(opts.write.clone());
    let mut index = ResourceIndex::new();
    let mut have_document = false;
    let mut have_meta = false;

    for &i in &order {
        let Some(f) = found.get(i) else { continue };
        let name = f.name.as_str();
        if name == MIMETYPE_ENTRY || name == MANIFEST_ENTRY {
            continue; // regenerated
        }
        let size = f.data.len() as u64;
        let digest_ok = row_of(name)
            .and_then(FileEntry::blake3)
            .map(|want| Digest::of(&f.data) == want);
        let res_path = parse_resource_path(name);
        let verdict = if !f.complete {
            Verdict::Truncated
        } else if !f.crc_ok {
            Verdict::CrcMismatch
        } else if res_path
            .as_ref()
            .is_some_and(|p| crate::resource::ResourceId::of(&f.data).short_hex() != p.short_hex)
        {
            Verdict::NameMismatch
        } else {
            match digest_ok {
                Some(true) => Verdict::Verified,
                Some(false) => Verdict::DigestMismatch,
                None => Verdict::Unchecked,
            }
        };
        let good = matches!(verdict, Verdict::Verified | Verdict::Unchecked);
        let mut action = Action::Dropped;
        if name == DOCUMENT_ENTRY {
            w.set_document(f.data.clone());
            have_document = true;
            action = if good { Action::Kept } else { Action::Salvaged };
            report.document_unverified = !good;
        } else if name == META_ENTRY {
            if good {
                w.set_meta(f.data.clone());
                have_meta = true;
                action = Action::Kept;
            }
        } else if good {
            action = carry(&mut w, &mut index, name, f, row_of(name));
        }
        report.entries.push(EntryReport {
            name: f.name.clone(),
            verdict,
            action,
            size,
        });
    }

    if !have_document {
        return Err(RepairError::NoDocument);
    }
    if !have_meta {
        w.set_meta(minimal_meta());
        report.entries.push(EntryReport {
            name: META_ENTRY.to_owned(),
            verdict: Verdict::Truncated,
            action: Action::Replaced,
            size: 0,
        });
    }
    w.add_resources(&index);
    let mut out = Cursor::new(Vec::new());
    w.finish(&mut out)?;
    let bytes = out.into_inner();
    report.bytes_written = bytes.len() as u64;
    Ok(Repaired { bytes, report })
}

/// Hands a verified, non-structural entry to the writer.
fn carry(
    w: &mut PackageWriter,
    index: &mut ResourceIndex,
    name: &str,
    f: &Found,
    row: Option<&FileEntry>,
) -> Action {
    if let Some(p) = parse_resource_path(name) {
        return match index.insert(p.kind, p.ext, f.data.clone()) {
            Ok(_) => Action::Kept,
            Err(_) => Action::Dropped,
        };
    }
    let ok = match group_of(name) {
        Group::Thumbnail => w.set_thumbnail(f.data.clone()).is_ok(),
        Group::Previews => name
            .strip_prefix("previews/spread-")
            .and_then(|s| s.strip_suffix(".png"))
            .and_then(|n| n.parse::<u32>().ok())
            .is_some_and(|n| w.set_preview(n, f.data.clone()).is_ok()),
        g => {
            let role = row.map(FileEntry::effective_role).unwrap_or(match g {
                Group::History => Role::History,
                Group::Extensions => Role::Extension,
                _ => Role::Unknown,
            });
            let media = row.map_or("application/octet-stream", |r| r.media_type.as_str());
            w.add_entry(name, media, role, f.data.clone()).is_ok()
        }
    };
    if ok { Action::Kept } else { Action::Dropped }
}

/// Reads `input`, rebuilds it and writes `output` atomically.
///
/// # Errors
///
/// As [`repair`], plus I/O errors.
pub fn repair_file(
    input: &Path,
    output: &Path,
    opts: &RepairOptions,
) -> Result<RepairReport, RepairError> {
    let bytes = std::fs::read(input)?;
    let r = repair(&bytes, opts)?;
    crate::durability::write_atomic(output, |f| {
        use std::io::Write;
        f.write_all(&r.bytes)?;
        Ok(())
    })?;
    Ok(r.report)
}
